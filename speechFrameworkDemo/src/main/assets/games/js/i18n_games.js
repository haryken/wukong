    let currentLang = 'vi';
    let applying = false;

    function normalizeLang(lang) {
        lang = String(lang || '').toLowerCase().trim();
        if (lang.startsWith('en')) return 'en';
        if (lang.startsWith('it')) return 'it';
        if (lang.startsWith('zh') || lang === 'cn') return 'zh';
        if (lang.startsWith('vi') || lang === 'vn') return 'vi';
        if (SUPPORTED.includes(lang)) return lang;
        return 'vi';
    }

    function t(key, fallback) {
        const pack = STRINGS[currentLang] || STRINGS.vi;
        if (pack[key] != null) return pack[key];
        if (STRINGS.en[key] != null) return STRINGS.en[key];
        if (STRINGS.vi[key] != null) return STRINGS.vi[key];
        return fallback != null ? fallback : key;
    }

    function getLang() {
        return currentLang;
    }

    function applyI18n(root) {
        const whole = !root || root === document;
        root = root || document;
        root.querySelectorAll('[data-i18n]').forEach((el) => {
            const key = el.getAttribute('data-i18n');
            if (!key) return;
            const val = t(key, el.textContent);
            if (el.getAttribute('data-i18n-html') === '1') {
                el.innerHTML = val;
            } else {
                el.textContent = val;
            }
        });
        root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (key) el.setAttribute('placeholder', t(key));
        });
        root.querySelectorAll('[data-i18n-title]').forEach((el) => {
            const key = el.getAttribute('data-i18n-title');
            if (key) el.setAttribute('title', t(key));
        });
        root.querySelectorAll('[data-i18n-value]').forEach((el) => {
            const key = el.getAttribute('data-i18n-value');
            if (key) el.value = t(key);
        });
        document.documentElement.setAttribute('lang', currentLang);
        document.documentElement.classList.add('i18n-pure');
        document.title = t('nav.games', 'Trò chơi') + ' — Alpha Mini';
        // Only a full-page apply notifies listeners: chess.js calls apply(list) from inside its
        // own 'wireos-i18n' handler, so dispatching on subtree applies would recurse forever.
        if (!whole || applying) return;
        applying = true;
        try {
            document.dispatchEvent(new CustomEvent('wireos-i18n', { detail: { lang: currentLang } }));
        } catch (_) {
        } finally {
            applying = false;
        }
    }

    function loadLang() {
        try {
            const cached = localStorage.getItem(STORAGE_KEY);
            if (cached) return normalizeLang(cached);
        } catch (_) {}
        return 'vi';
    }

    async function setLang(lang, { persist = true } = {}) {
        currentLang = normalizeLang(lang);
        const sel = document.getElementById('uiLangSelect');
        if (sel && sel.value !== currentLang) sel.value = currentLang;
        applyI18n(document);
        if (persist) {
            try {
                localStorage.setItem(STORAGE_KEY, currentLang);
            } catch (_) {}
        }
        return currentLang;
    }

    function bindLangSelect() {
        const sel = document.getElementById('uiLangSelect');
        if (!sel || sel._i18nBound) return;
        sel._i18nBound = true;
        sel.addEventListener('change', () => {
            setLang(sel.value, { persist: true });
        });
    }

    function initI18n() {
        bindLangSelect();
        currentLang = loadLang();
        const sel = document.getElementById('uiLangSelect');
        if (sel) sel.value = currentLang;
        applyI18n(document);
        // Re-apply soon after other scripts mutate labels
        setTimeout(() => applyI18n(document), 50);
        setTimeout(() => applyI18n(document), 400);
    }

    currentLang = loadLang();

    global.I18N = {
        t,
        getLang,
        setLang,
        apply: applyI18n,
        init: initI18n,
        STRINGS,
        SUPPORTED,
    };
    global.t = t;

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initI18n);
    } else {
        initI18n();
    }
